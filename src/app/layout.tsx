import type { Metadata, Viewport } from "next";
import { Pixelify_Sans, Silkscreen } from "next/font/google";
import { FireCursor } from "@/components/ui/FireCursor";
import "./globals.css";

const pixelify = Pixelify_Sans({ subsets: ["latin"], variable: "--font-pixelify", display: "swap" });
// Blocky digits that never read as letters (Pixelify's 5/S and 2/8 are too close at small sizes).
const silkscreen = Silkscreen({ subsets: ["latin"], weight: ["400", "700"], variable: "--font-silkscreen", display: "swap" });

// Absolute URLs for share previews: the deployment's own URL, overridable with NEXT_PUBLIC_SITE_URL.
const siteUrl =
  process.env.NEXT_PUBLIC_SITE_URL ??
  (process.env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}` : "http://localhost:3000");

// Favicons come from the app-directory files (favicon.ico, icon.svg, icon1.png, apple-icon.png), the share
// image from opengraph-image.png / twitter-image.png, all generated by scripts/make-icons.mjs from
// the flame cursor (icon1.png is a 32px PNG for browsers without SVG favicons).
export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title: "Chog Raid",
  description: "Every Chog becomes a room in one giant shared dungeon. Defend yours, raid others.",
  openGraph: {
    title: "Chog Raid",
    description: "Every Chog is a dungeon room. Defend yours. Raid the rest.",
    type: "website",
    siteName: "Chog Raid",
  },
  twitter: { card: "summary_large_image", title: "Chog Raid", description: "Every Chog is a dungeon room. Defend yours. Raid the rest." },
};

export const viewport: Viewport = { width: "device-width", initialScale: 1, themeColor: "#120d0a" };

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${pixelify.variable} ${silkscreen.variable}`}>
      <body>
        {children}
        <FireCursor />
      </body>
    </html>
  );
}
